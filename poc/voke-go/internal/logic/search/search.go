// Package search 是查询过滤接缝（view 层与匹配引擎之间的唯一切面）——
// §7.2 步骤3 从 view.go（package main）原样搬来，匹配语义、截断上限、
// search key 构造逐字不变（这是 §6.2 V2 命脉的行为，评分 / 去重 / 拼音调用
// 一个都不动）。
//
// 分层：本包属 logic 层，**零 mygo、零 x/sys/windows**；只依赖标准库、
// internal/match（同为非平台层，允许 import）与 internal/logic/appsmodel
// （AppEntry 类型来源）。这样 `go test ./internal/logic/...` 在 Linux 原生可跑。
package search

import (
	"cmp"
	"slices"
	"strings"

	"github.com/zyition/voke/poc/voke-go/internal/logic/appsmodel"
	"github.com/zyition/voke/poc/voke-go/internal/logic/frequency"
	"github.com/zyition/voke/poc/voke-go/internal/match"
)

// appSearchKeys 是应用名搜索键的有界记忆化缓存，对应 voke-core 的
// SearchKeysCache（CAPACITY=512，超限整表清空）。FilterApps 每次查询
// 整体收到 []appsmodel.AppEntry（无索引期预计算钩子），键生成走缓存复用，避免
// 每次按键都对全量应用重算多音字展开。接入方式对照生产 voke 的
// windows/workspace/terminal provider（条目每次查询重建 → 键走缓存），
// 与 apps provider 的「索引期预计算」相比无需改 AppEntry 契约本身。
var appSearchKeys = match.NewSearchKeysCache()

// matchMaxResults 对应 voke-core/src/apps.rs AppsProvider::MAX_RESULTS：
// 非空查询的结果条数上限（空查询不限流，与生产一致）。
const matchMaxResults = 50

// FilterApps 是查询过滤 + 排序接缝（view 层与匹配引擎之间的唯一切面）。
//
// 它折叠了生产里分成两步的东西：apps provider 的 `query()`（apps.rs:223-254）
// 与 `QueryEngine::rank`（engine.rs:470，aggregate 里对每个批次调）。生产把频率
// 加成放在 rank 而非 provider（apps.rs:22 明确「频率排序不在这里」），但 Go 的
// apps 走 panelstate 老路径、不经 Registry.Aggregate，故这条老路径的 rank 就并进
// FilterApps，用 [frequency.Store] 现算——apps-only 全局查询因此也能「越用越靠前」，
// 与生产一致。
//
// 行为 1:1 对照生产：
//   - 空查询（trim 后为空）：全量、score 恒 1.0、**不截断**，但照样按
//     `frequency_boost` 降序稳定排（常用应用置顶；boost 相同则保枚举序）；
//   - 非空查询：逐条目 ScoreEntry → 按原始分降序稳定排 → **截断到 matchMaxResults
//     （截断在 boost 之前**，被截掉的高频项不复活，对照 apps.rs:247-254）→ 再按
//     `score × boost` 降序稳定排（apps 内 weight 恒定，折进 rank 会约掉，故省略）；
//   - 搜索键以 app.Name 为主（SearchKeys::from_name）；另以条目 ID 的英文文件名
//     词干作**补充键**（本地化显示名如「服务」也可用 service 搜到，见 appAlias）。
//
// freq 为 nil（未装配频率表 / 纯逻辑测试）→ boost 恒 1.0，排序退化成「只按原始分、
// 空查询保枚举序」，与引入本参数之前逐字一致。
//
// 线程：只在主线程调用（view 帧内或 Window.Update 回调内）；
// SearchKeysCache 自身有锁，命中返回同一实例（对应 Rust 的 Arc）。
func FilterApps(query string, apps []appsmodel.AppEntry, freq frequency.Store) []appsmodel.AppEntry {
	q := strings.TrimSpace(query)
	if q == "" {
		out := make([]appsmodel.AppEntry, len(apps))
		copy(out, apps)
		slices.SortStableFunc(out, func(a, b appsmodel.AppEntry) int {
			return cmp.Compare(boostOf(freq, b.Name), boostOf(freq, a.Name))
		})
		return out
	}
	m := match.NewMatcher()
	type scored struct {
		app   appsmodel.AppEntry
		score float32
	}
	found := make([]scored, 0, len(apps))
	for _, app := range apps {
		best, ok := match.ScoreEntry(m, q, appSearchKeys.Get(app.Name))
		// 英文文件名兜底：AppsFolder 的显示名是本地化的（如「服务」），但条目 ID
		// 常带可执行/文件名字干（`…\services.msc`、`…\regedit.exe`）。以该词干作补充
		// 键、取分高者，恢复「service / regedit」这类按程序名搜索。AutoGenerated
		// 占位项与 AUMID 没有可用英文名，跳过（见 appAlias）。
		if alias := appAlias(app.ID); alias != "" && alias != app.Name {
			if s2, ok2 := match.ScoreEntry(m, q, appSearchKeys.Get(alias)); ok2 && (!ok || s2.Score > best.Score) {
				best, ok = s2, true
			}
		}
		if ok {
			found = append(found, scored{app, best.Score})
		}
	}
	slices.SortStableFunc(found, func(a, b scored) int { return cmp.Compare(b.score, a.score) })
	if len(found) > matchMaxResults {
		found = found[:matchMaxResults]
	}
	slices.SortStableFunc(found, func(a, b scored) int {
		return cmp.Compare(a.score*float32(boostOf(freq, b.app.Name)),
			b.score*float32(boostOf(freq, a.app.Name)))
	})
	out := make([]appsmodel.AppEntry, 0, len(found))
	for _, f := range found {
		out = append(out, f.app)
	}
	return out
}

// boostOf 取某应用名的频率排序乘数：nil 表 / 未记录过 → 1.0（对照 frequency.Boost(0)）。
// 键前缀固定用 appsmodel.ProviderID，与启动侧 record 的键必须一致，否则记了加不上。
func boostOf(freq frequency.Store, name string) float64 {
	if freq == nil {
		return 1.0
	}
	return freq.BoostOf(frequency.Key(appsmodel.ProviderID, name))
}

// appAlias 从条目 ID 取英文文件名词干作为 name 之外的补充匹配键
// （实现见 appsmodel.AppIDStem：`…\services.msc`→services）。
func appAlias(id string) string { return appsmodel.AppIDStem(id) }
