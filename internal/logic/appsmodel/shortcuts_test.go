func TestLooksLikeSentence(t *testing.T) {
	cases := []struct {
		s    string
		want bool
	}{
		{"Visual Studio Code", false},
		{"轻松发现、直观显示和共享数据中的见解。", true},
		{"执行基于对象的函数；", true},
		{"Node.js", false}, // 中间的点不算
		{"Hello!", true},
		{"", false},
	}
	for _, c := range cases {
		if got := LooksLikeSentence(c.s); got != c.want {
			t.Errorf("LooksLikeSentence(%q) = %v，想要 %v", c.s, got, c.want)
		}
	}
}

func TestShortcutName(t *testing.T) {
	// 描述与文件名共享词 → 用描述（保留大小写/空格）。
	if got := ShortcutName("Visual Studio Code", "Visual Studio Code"); got != "Visual Studio Code" {
		t.Errorf("可信描述应采纳，得到 %q", got)
	}
	// 营销长句 → 退回文件名。
	if got := ShortcutName("轻松发现、直观显示和共享数据中的见解。", "Excel"); got != "Excel" {
		t.Errorf("营销文案应退回文件名，得到 %q", got)
	}
	// 空描述 → 文件名。
	if got := ShortcutName("", "services"); got != "services" {
		t.Errorf("空描述应退回文件名，得到 %q", got)
	}
}

