func TestMergeShortcutAppsNoMutualElimination(t *testing.T) {
	// 微信：.lnk 名「微信」目标 …\Weixin.exe；AppsFolder 也名「微信」ID …\Weixin.exe。
	// 旧逻辑 rule-2 删 AppsFolder、词干关联又删 .lnk → 两边互删、应用消失。应恰留一条。
	shortcuts := []AppEntry{{Name: "微信", Path: `C:\...\微信.lnk`, Target: `C:\Program Files\Tencent\Weixin\Weixin.exe`}}
	installed := []AppEntry{{
		Name: "微信", Path: `shell:AppsFolder\{G}\Tencent\Weixin\Weixin.exe`,
		ID: `{6D809377-6AF0-444B-8957-A3773F02200E}\Tencent\Weixin\Weixin.exe`,
	}}
	got := MergeShortcutApps(installed, shortcuts)
	if len(got) != 1 || got[0].Name != "微信" {
		t.Fatalf("微信应恰好保留一条，得到 %+v", got)
	}
	if got[0].Path == shortcuts[0].Path {
		t.Error("应保留 AppsFolder 那条（带 ID，可中文/拼音搜），而不是删剩 .lnk")
	}
	// 微信开发者工具同理（ID 末段是中文 exe 名）。
	sc2 := []AppEntry{{Name: "微信开发者工具", Path: `C:\...\微信开发者工具.lnk`, Target: `C:\Program Files\Tencent\微信web开发者工具\微信开发者工具.exe`}}
	in2 := []AppEntry{{
		Name: "微信开发者工具", Path: `shell:AppsFolder\{G2}\Tencent\微信web开发者工具\微信开发者工具.exe`,
		ID: `{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\Tencent\微信web开发者工具\微信开发者工具.exe`,
	}}
	if got := MergeShortcutApps(in2, sc2); len(got) != 1 || got[0].Name != "微信开发者工具" {
		t.Fatalf("微信开发者工具应恰好保留一条，得到 %+v", got)
	}
}

func TestMergeShortcutApps(t *testing.T) {
	shortcuts := []AppEntry{
		{Name: "services", Path: `C:\...\services.lnk`, Target: `C:\Windows\System32\services.msc`},
		{Name: "Task Manager", Path: `C:\...\Task Manager.lnk`, Target: `C:\Windows\System32\taskmgr.exe`},
	}
	installed := []AppEntry{
		// 同一程序（ID 词干 services == .lnk 目标词干）：保留这条，跳过 .lnk。
		{Name: "服务", Path: `shell:AppsFolder\{G}\services.msc`, ID: `{1AC14E77}\services.msc`},
		// AutoGenerated：由 .lnk 代表，跳过。
		{Name: "任务管理器", Path: `shell:AppsFolder\AG`, ID: `Microsoft.AutoGenerated.{5E8F}`},
		{Name: "Chrome", Path: `shell:AppsFolder\Chrome`, ID: "Chrome"},
	}
	got := MergeShortcutApps(installed, shortcuts)
	// 期望：Task Manager(lnk) + 服务 + 任务管理器(AutoGenerated，保留本地化名) + Chrome。
	if len(got) != 4 {
		t.Fatalf("合并条数 = %d，期望 4；结果=%+v", len(got), got)
	}
	if got[0].Name != "Task Manager" {
		t.Errorf("剩余 .lnk 应排在前：%+v", got)
	}
	names := make(map[string]bool, len(got))
	for _, a := range got {
		names[a.Name] = true
	}
	if !names["服务"] || !names["Chrome"] || !names["任务管理器"] {
		t.Errorf("应保留 服务 / Chrome / 任务管理器：%+v", got)
	}
	if names["services"] {
		t.Error("services.lnk 已被 AppsFolder 条覆盖，不应重复出现")
	}

	// rule-2：非 MSIX 且与 .lnk 同名、但不是同一程序（词干不同）→ 跳过 AppsFolder 条。
	inst2 := []AppEntry{{Name: "Foo App", Path: `shell:AppsFolder\X`, ID: "Some.Win32"}}
	sc2 := []AppEntry{{Name: "Foo App", Path: `C:\...\Foo.lnk`, Target: `C:\x\other.exe`}}
	if got := MergeShortcutApps(inst2, sc2); len(got) != 1 || got[0].Path != sc2[0].Path {
		t.Errorf("rule-2 应保留 .lnk 那条：%+v", got)
	}
	// MSIX 与 .lnk 同名 → 保留（不按同名误删）。
	inst3 := []AppEntry{{Name: "Foo App", Path: `shell:AppsFolder\M`, ID: "Package!App"}}
	if got := MergeShortcutApps(inst3, sc2); len(got) != 2 {
		t.Errorf("MSIX 同名应保留：%+v", got)
	}
	// 无快捷方式 → 原样返回。
	if got := MergeShortcutApps(installed, nil); len(got) != len(installed) {
		t.Errorf("无快捷方式时应原样返回，得到 %d 条", len(got))
	}
}
