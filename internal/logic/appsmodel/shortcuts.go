// shortcuts.go：开始菜单 .lnk 与 AppsFolder 条目的**跨来源合并**纯逻辑（对照
// voke-sys/src/apps.rs 的 load_all_apps）。真正的 .lnk 解析（COM）在 platform 层，
// 本文件只做可跨平台单测的判定：命名、可启动性、双源去重。
package appsmodel

import (
	"path/filepath"
	"strings"
)

// executableExts 是「目标扩展名可启动」白名单（对照 Rust EXECUTABLE_EXTS；不含 lnk，
// 嵌套快捷方式不可启动）。
var executableExts = map[string]struct{}{
	"exe": {}, "com": {}, "bat": {}, "cmd": {}, "ps1": {}, "msc": {}, "cpl": {},
	"msi": {}, "msp": {}, "mst": {}, "scr": {}, "pif": {}, "bin": {}, "job": {},
	"sct": {}, "ws": {}, "wsh": {}, "wsf": {}, "vb": {}, "vbe": {}, "vbs": {},
	"js": {}, "jse": {}, "appref-ms": {},
}

// documentExts 是明确的数据/文档扩展名：命中即剔除（对照 Rust DOCUMENT_EXTS）。
var documentExts = map[string]struct{}{
	"txt": {}, "pdf": {}, "html": {}, "htm": {}, "url": {}, "chm": {}, "hlp": {}, "md": {},
	"ini": {}, "inf": {}, "rtf": {}, "doc": {}, "docx": {}, "xls": {}, "xlsx": {}, "ppt": {},
	"pptx": {}, "csv": {}, "log": {}, "json": {}, "xml": {}, "yml": {}, "yaml": {}, "toml": {},
	"jpg": {}, "jpeg": {}, "png": {}, "gif": {}, "bmp": {}, "svg": {}, "ico": {}, "mp3": {},
	"mp4": {}, "mkv": {}, "avi": {}, "zip": {}, "7z": {}, "rar": {},
}

// LooksLikeSentence 判断字符串是否是「一整句话」而非名字（对照 Rust looks_like_sentence）：
// CJK 句末标点出现在任意位置、或 ASCII 的 .!?; 收尾。
func LooksLikeSentence(s string) bool {
	t := strings.TrimSpace(s)
	if t == "" {
		return false
	}
	if strings.ContainsAny(t, "。；！？") {
		return true
	}
	last := t[len(t)-1]
	return last == '.' || last == '!' || last == '?' || last == ';'
}

// PlausibleDescription 判断 .lnk 的 description 是否适合作显示名（对照 Rust
// is_plausible_name）：非空、不像整句话、且与文件名词干至少共享一个词
// （防 Office 那类营销文案把真实名字顶掉）。
func PlausibleDescription(description, fileStem string) bool {
	d := strings.TrimSpace(description)
	if d == "" || LooksLikeSentence(d) {
		return false
	}
	stw := words(fileStem)
	if len(stw) == 0 {
		return false
	}
	for _, dw := range words(d) {
		for _, sw := range stw {
			if dw == sw {
				return true
			}
		}
	}
	return false
}

func words(s string) []string {
	fields := strings.FieldsFunc(strings.ToLower(s), func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r >= 'A' && r <= 'Z')
	})
	out := fields[:0]
	for _, w := range fields {
		if w != "" {
			out = append(out, w)
		}
	}
	return out
}

// ShortcutName 选 .lnk 的显示名：description 可信则用，否则退回文件名去 .lnk。
func ShortcutName(description, fileStem string) string {
	if PlausibleDescription(description, fileStem) {
		return strings.TrimSpace(description)
	}
	return strings.TrimSpace(fileStem)
}

// LaunchableTarget 判断 .lnk 解析出的目标是否值得收录（对照 Rust is_launchable_target）。
// 空目标（外壳项，如资源管理器/控制面板）**收录**——我们启动的是 .lnk 本体，shell 会解析。
func LaunchableTarget(target string, existsDir bool) bool {
	if strings.TrimSpace(target) == "" {
		return true // 外壳项 / 仅 PIDL 的快捷方式：交给 shell 启动 .lnk 本身
	}
	ext := strings.ToLower(strings.TrimPrefix(filepath.Ext(target), "."))
	if _, ok := executableExts[ext]; ok {
		return true
	}
	if _, ok := documentExts[ext]; ok {
		return false
	}
	if ext == "" {
		return true // 裸命令 / 目录
	}
	return existsDir
}

// AppIDStem 取 AppsFolder 条目 ID / .lnk 目标路径里的文件名词干（小写、去扩展名）。
// AUMID（含 '!'）、AutoGenerated 占位、纯 GUID 段没有可用文件名 → 空串。
// 用途有二：应用的英文检索别名（services.msc→services），以及跨来源去重。
func AppIDStem(id string) string {
	if id == "" || strings.HasPrefix(id, "Microsoft.AutoGenerated.") || strings.Contains(id, "!") {
		return ""
	}
	base := id
	if i := strings.LastIndexAny(base, `\/`); i >= 0 {
		base = base[i+1:]
	}
	if base == "" || strings.HasPrefix(base, "{") {
		return ""
	}
	if i := strings.LastIndex(base, "."); i > 0 {
		base = base[:i]
	}
	return strings.ToLower(base)
}

// MergeShortcutApps 合并两来源（对照 Rust load_all_apps，并额外按**目标文件名**做跨
// 来源去重，避免同一程序两行、且中英文都能搜）：
//   - 同一程序：.lnk 目标词干（services）== AppsFolder ID 词干（services.msc）→ 保留
//     AppsFolder 那条（本地化名 + ID 英文别名），跳过该 .lnk；
//   - 剩余 .lnk 条目排在前面（与 Rust 的 lnk 优先一致）；
//   - rule-2：非 MSIX（ID 不含 '!'）且与某 .lnk 同名的 AppsFolder 条跳过。
//
// 与 Rust 的有意差异：**不丢** `Microsoft.AutoGenerated.*` 条目（任务管理器/任务计划
// 程序等）。Rust 靠 .lnk 的英文名代表它们，会丢掉本地化名 → 中文/拼音搜不到；这里
// 保留本地化条目，英文 `.lnk` 也保留（两者名字不同，过滤态不会同屏；空查询全量列表
// 可能各出现一次）。这是「宁全勿丢」的取舍。
func MergeShortcutApps(installed, shortcuts []AppEntry) []AppEntry {
	if len(shortcuts) == 0 {
		return installed
	}
	installedStems := make(map[string]struct{}, len(installed))
	for _, a := range installed {
		if st := AppIDStem(a.ID); st != "" {
			installedStems[st] = struct{}{}
		}
	}
	out := make([]AppEntry, 0, len(shortcuts)+len(installed))
	// rule-2 只能针对**实际保留**的 .lnk：若某 .lnk 因与 AppsFolder 同程序（词干相同）
	// 而被跳过，就不能再用它的名字去删同名 AppsFolder 条——否则两边互删、应用消失
	//（微信：.lnk「微信」→ …\Weixin.exe，AppsFolder「微信」ID 也是 Weixin.exe）。
	keptLnkNames := make(map[string]struct{}, len(shortcuts))
	for _, s := range shortcuts {
		if st := AppIDStem(s.Target); st != "" {
			if _, covered := installedStems[st]; covered {
				continue // 同一程序已有 AppsFolder 条：不重复
			}
		}
		out = append(out, s)
		keptLnkNames[strings.ToLower(strings.TrimSpace(s.Name))] = struct{}{}
	}
	for _, a := range installed {
		if !strings.Contains(a.ID, "!") {
			if _, dup := keptLnkNames[strings.ToLower(strings.TrimSpace(a.Name))]; dup {
				continue // rule-2：与**保留的** .lnk 同名，交给 .lnk
			}
		}
		out = append(out, a)
	}
	return out
}
